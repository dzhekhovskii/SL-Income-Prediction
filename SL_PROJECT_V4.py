BINS = np.linspace(0, 1, 11)


def tranches(proba):
    """Numéro de tranche (0 à 9) ; 0 et 1 inclus grâce à np.digitize."""
    return np.digitize(proba, BINS[1:-1])


def calcul_ece(y_vrai, proba):
    y_vrai, proba = np.asarray(y_vrai), np.asarray(proba)
    t = tranches(proba)
    ece = 0
    for b in range(len(BINS) - 1):
        m = t == b
        if m.any():
            ece += m.mean() * abs(proba[m].mean() - y_vrai[m].mean())
    return ece


