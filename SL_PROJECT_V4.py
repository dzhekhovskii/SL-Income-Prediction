    duree = time.time() - debut

    res = evaluer(pipe, nom)
    res["Temps (s)"] = duree
    resultats_etape4.append(res)
    pipelines_etape4[nom] = pipe
    print(f"{nom} entraîné en {duree:.1f} s")

