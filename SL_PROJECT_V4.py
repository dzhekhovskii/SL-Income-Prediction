"""### Conclusion

* Les 3 versions ont **la même PR-AUC (≈ 0,77) et la même ROC-AUC (0,907)** : elles classent les individus exactement de la même façon.
* `class_weight` et SMOTE ne rendent donc pas le modèle meilleur : ils **déplacent seulement le seuil de décision** (plus de recall, moins de precision).
* Or déplacer le seuil, on peut le faire **directement**, sans toucher à l'entraînement. Repondérer les classes a en plus un effet secondaire : le modèle apprend sur une distribution artificielle, ce qui **gonfle ses probabilités** (on le vérifie à l'étape 9).

**Choix retenu : pas de repondération.** On garde le modèle simple, et on traite le déséquilibre :
1. avec des **métriques adaptées** (PR-AUC pour choisir les modèles, recall et precision pour la décision) ;
2. avec un **réglage du seuil de décision** selon le coût des erreurs (section « Choix du seuil »), l'intervention la moins invasive.

## Étape 4 : Progression des modèles

On compare 3 modèles de complexité croissante, évalués sur la validation avec les mêmes métriques :

1. **Régression logistique** : modèle linéaire simple et interprétable (baseline).
2. **Random Forest** : ensemble d'arbres, capte les relations non linéaires et les interactions.
3. **XGBoost** : arbres construits les uns après les autres, chacun corrigeant les erreurs du précédent (boosting).

Les modèles sont entraînés **sans repondération des classes** (choix de l'étape 3). On les compare sur la **PR-AUC**, qui ne dépend pas du seuil. Le recall et la precision sont donnés au seuil de 0,5 à titre indicatif : le seuil sera réglé plus loin.
"""

import time
from sklearn.ensemble import RandomForestClassifier
