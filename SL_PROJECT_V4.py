"""### Fonction d'évaluation
Cette fonction calcule les métriques d'un modèle sur la validation.
"""

from sklearn.metrics import precision_score, f1_score, average_precision_score, roc_auc_score

def evaluer(modele, nom):
    y_pred = modele.predict(X_val)               # classe prédite (0 ou 1), seuil 0,5
    y_proba = modele.predict_proba(X_val)[:, 1]  # probabilité d'être >50K
    return {
        "Modèle": nom,
        "Accuracy": accuracy_score(y_val, y_pred),
        "Precision": precision_score(y_val, y_pred),
        "Recall": recall_score(y_val, y_pred),
        "F1": f1_score(y_val, y_pred),
        "PR-AUC": average_precision_score(y_val, y_proba),
        "ROC-AUC": roc_auc_score(y_val, y_proba),
    }

print("Fonction evaluer() prête")

