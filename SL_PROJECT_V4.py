"""**Justification des features créées** *

* **is_married** : le taux de `>50K` est bien plus élevé chez les personnes mariées (revenus du foyer, âge, stabilité professionnelle).
* **has_capital / net_capital** : avoir des revenus du capital est un marqueur fort de revenu élevé. L'indicateur binaire est plus robuste que le montant brut, qui contient surtout des zéros et quelques valeurs extrêmes.
* **hours_group** : la relation entre heures et revenu n'est pas linéaire. Le regroupement aide la régression logistique à capter l'effet des heures supplémentaires.
* **workclass regroupé** et **is_us** : on réduit le nombre de modalités rares, ce qui limite le surapprentissage après le One-Hot Encoding.

### Préparation du Pipeline de prétraitement

* **Variables numériques** : imputation par la médiane, puis **StandardScaler**.
* **Variables catégorielles** : imputation par la modalité la plus fréquente, puis **OneHotEncoder** (`handle_unknown="ignore"` pour les modalités jamais vues dans le train).
"""

from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import FunctionTransformer, OneHotEncoder, StandardScaler

NUM_COLS = ["age", "education-num", "capital-gain", "capital-loss", "hours-per-week",
            "net_capital", "has_capital", "is_married", "is_us"]
CAT_COLS = ["workclass", "occupation", "relationship", "race", "sex", "hours_group"]

numeric = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler()),
])
categorical = Pipeline([
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False)),
])
preprocessor = Pipeline([
    ("features", FunctionTransformer(add_features)),
    ("columns", ColumnTransformer([
        ("num", numeric, NUM_COLS),
        ("cat", categorical, CAT_COLS),
    ])),
])

"""### Séparation des données

Comme dans le cours de ML I, on sépare les features (`X`) et la cible (`y`), puis on fait un **split stratifié** pour conserver la proportion 76 / 24 dans chaque jeu :
* **60 % train** : entraînement et validation croisée ;
* **20 % validation** : comparaison des modèles ;
* **20 % test** : évaluation finale uniquement, **on n'y touche plus d'ici là**.

On définit aussi la **validation croisée stratifiée à 5 folds** qui servira pour le tuning.
"""

from sklearn.model_selection import train_test_split, StratifiedKFold

RANDOM_STATE = 42
X = df.drop(columns=["income"])
